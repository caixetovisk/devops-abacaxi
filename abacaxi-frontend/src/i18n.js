const ERROS_API = {
  'Failed to fetch': 'connecting',
  'Erro na requisição': 'requestError',
  'Erro interno no servidor': 'serverError',
  'Usuário ou senha inválidos': 'invalidCredentials',
  'Token não informado': 'missingToken',
  'Token inválido ou expirado': 'invalidToken',
  'Colheita não encontrada': 'harvestNotFound',
  'Venda não encontrada': 'saleNotFound',
  'Não é possível excluir: os abacaxis desta colheita já foram vendidos': 'deleteHarvestStock',
  'Informe a data e uma quantidade maior que zero': 'invalidHarvest',
  'Informe data, quantidade e preço maiores que zero': 'invalidSale',
};

export function traduzirErro(mensagem, idioma) {
  const chave = ERROS_API[mensagem];
  if (chave) return TRADUCOES[idioma][chave];

  const estoque = mensagem.match(/^Estoque insuficiente\. Disponível: (.+)$/);
  if (estoque) return TRADUCOES[idioma].insufficientStock(estoque[1]);

  return mensagem;
}

export function formatarData(data, idioma) {
  const [ano, mes, dia] = data.split('-').map(Number);
  return new Intl.DateTimeFormat(IDIOMAS[idioma].locale, {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date(ano, mes - 1, dia));
}

export function formatarReais(valor, idioma) {
  return Number(valor).toLocaleString(IDIOMAS[idioma].locale, {
    style: 'currency',
    currency: IDIOMAS[idioma].moeda,
  });
}
